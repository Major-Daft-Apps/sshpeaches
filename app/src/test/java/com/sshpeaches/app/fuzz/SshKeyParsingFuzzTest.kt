/**
 * Fuzzes the key helpers. Documented invalid-input path: `null` from
 * [computeSshPublicKeyFingerprint] and [SshKeyGenerator.derivePublicKeyFromPrivate].
 */
class SshKeyParsingFuzzTest {

    companion object {
        private val generated by lazy {
            listOf(
                SshKeyGenerator.generate(IdentityKeyGenerationSpec(IdentityKeyAlgorithm.ED25519, comment = "ed")),
                SshKeyGenerator.generate(IdentityKeyGenerationSpec(IdentityKeyAlgorithm.RSA, rsaBits = 2048, comment = "rsa")),
                SshKeyGenerator.generate(IdentityKeyGenerationSpec(IdentityKeyAlgorithm.ECDSA, ecdsaCurve = IdentityEcdsaCurve.P256)),
                SshKeyGenerator.generate(IdentityKeyGenerationSpec(IdentityKeyAlgorithm.ECDSA, ecdsaCurve = IdentityEcdsaCurve.P521))
            )
        }

        fun pem(type: String, body: ByteArray): String =
            "-----BEGIN $type-----\n" + Base64.getEncoder().encodeToString(body).chunked(64).joinToString("\n") +
                "\n-----END $type-----\n"

        /** Deterministic 1024-bit RSA CRT values with the given public exponent [e]. */
        fun rsaPkcs1(e: BigInteger): RSAPrivateKey {
            val rnd = java.util.Random(1)
            val p = BigInteger.probablePrime(512, rnd)
            val q = BigInteger.probablePrime(512, rnd)
            val n = p.multiply(q)
            val phi = p.subtract(BigInteger.ONE).multiply(q.subtract(BigInteger.ONE))
            val d = BigInteger.valueOf(65_537).modInverse(phi) // any value; only parsed, never used
            return RSAPrivateKey(
                n, e, d, p, q,
                d.mod(p.subtract(BigInteger.ONE)), d.mod(q.subtract(BigInteger.ONE)), q.modInverse(p)
            )
        }

        fun derSequence(vararg values: BigInteger): ByteArray =
            DERSequence(ASN1EncodableVector().apply { values.forEach { add(ASN1Integer(it)) } }).encoded
    }

    private fun derive(material: String, passphrase: String? = null): String? =
        Fuzz.guarded("derivePublicKeyFromPrivate", material) {
            SshKeyGenerator.derivePublicKeyFromPrivate(material, passphrase = passphrase)
        }

    private fun fingerprint(text: String): String? =
        Fuzz.guarded("computeSshPublicKeyFingerprint", text) { computeSshPublicKeyFingerprint(text) }

    // ---------------- fingerprints ----------------

    @Test
    fun generatedKeys_fingerprintMatchesBlobHash_andValidatorAccepts() {
        generated.forEach { key ->
            val blob = Base64.getDecoder().decode(key.publicKey.split(' ')[1])
            val expected = "SHA256:" + Base64.getEncoder().withoutPadding()
                .encodeToString(MessageDigest.getInstance("SHA-256").digest(blob))
            assertEquals(expected, key.fingerprint)
            assertEquals(expected, fingerprint(key.publicKey))
            assertEquals(expected, fingerprint("# comment\n\n  ${key.publicKey}  \r\n"))
            assertTrue(isValidFingerprint(key.fingerprint))
        }
    }

    @Test
    fun mutatedPublicKeys_neverThrow_andAnyResultPassesValidator() {
        val random = Random(Fuzz.DEFAULT_SEED + 10)
        val seeds = generated.map { it.publicKey } + listOf(
            "ssh-ed25519", "ssh-rsa  ", "", "#", "AAAA", "sk-ssh-ed25519@openssh.com AAAA x",
            "from=\"1.2.3.4\" ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIA== c"
        )
        repeat(5_000) {
            val base = seeds.random(random)
            val input = when (random.nextInt(3)) {
                0 -> Fuzz.mutateString(random, base)
                1 -> base.substringBefore(' ') + " " + Fuzz.mutateBase64(random, base.substringAfter(' ').substringBefore(' '))
                else -> Fuzz.randomString(random, 80)
            }
            val result = fingerprint(input)
            if (result != null) {
                assertTrue("validator rejects computed fingerprint $result for ${Fuzz.describe(input)}", isValidFingerprint(result))
            }
        }
        fingerprint("ssh-ed25519 " + "A".repeat(4_000_000))
    }

    // ---------------- private key derivation ----------------

    @Test
    fun generatedKeys_derivedPublicKeyMatches() {
        generated.forEach { key ->
            val derived = derive(key.privateKey)
            assertEquals(key.publicKey.split(' ').take(2).joinToString(" "), derived)
            // CRLF line endings and surrounding junk.
            assertEquals(derived, derive("junk\r\n" + key.privateKey.replace("\n", "\r\n") + "\r\ntrailer"))
        }
        val encrypted = SshKeyGenerator.generate(IdentityKeyGenerationSpec(IdentityKeyAlgorithm.ED25519, keyPassphrase = "correct horse"))
        assertTrue(encrypted.privateKey.contains("ENCRYPTED PRIVATE KEY"))
        assertNull(derive(encrypted.privateKey, passphrase = null))
        assertNull(derive(encrypted.privateKey, passphrase = "wrong"))
        val withPassphrase = derive(encrypted.privateKey, passphrase = "correct horse")
        println("encrypted PKCS#8 derive with correct passphrase on this JVM: ${withPassphrase != null}")
    }

    @Test
    fun openSshV1Ed25519_derivesAndSurvivesMutation() {
        val random = Random(Fuzz.DEFAULT_SEED + 11)
        val priv = Ed25519PrivateKeyParameters(ByteArray(32) { it.toByte() }, 0)
        val blob = OpenSSHPrivateKeyUtil.encodePrivateKey(priv)
        val material = pem("OPENSSH PRIVATE KEY", blob)
        assertNotNull(derive(material))
        repeat(3_000) {
            derive(pem("OPENSSH PRIVATE KEY", Fuzz.mutateBytes(random, blob)))
        }
    }

    @Test
    fun mutatedPrivateKeys_neverThrowOrHang() {
        val random = Random(Fuzz.DEFAULT_SEED + 12)
        val types = listOf("PRIVATE KEY", "RSA PRIVATE KEY", "EC PRIVATE KEY", "DSA PRIVATE KEY", "OPENSSH PRIVATE KEY", "ENCRYPTED PRIVATE KEY", "X")
        val bodies = generated.map { key ->
            Base64.getDecoder().decode(key.privateKey.lines().filterNot { it.startsWith("-----") }.joinToString(""))
        }
        val failures = mutableListOf<String>()
        repeat(4_000) {
            val body = bodies.random(random)
            val mutated = if (random.nextInt(5) == 0) body else Fuzz.mutateBytes(random, body)
            val text = if (random.nextInt(4) == 0) Fuzz.mutateString(random, pem(types.random(random), mutated)) else pem(types.random(random), mutated)
            try {
                derive(text)
            } catch (e: AssertionError) {
                failures += e.message.orEmpty().lineSequence().first()
            }
        }
        assertTrue("derive threw/hung on ${failures.size} mutated keys, e.g.\n" + failures.distinct().take(10).joinToString("\n"), failures.isEmpty())
    }

    @Test
    fun pemRegex_scalingProbe() {
        // Prints how long the PEM regex takes for k unmatched BEGIN lines (O(k * length)).
        listOf(250, 500, 1_000).forEach { k ->
            val text = "-----BEGIN RSA PRIVATE KEY-----\n".repeat(k) + "AAAA"
            val start = System.nanoTime()
            SshKeyGenerator.derivePublicKeyFromPrivate(text)
            println("PEM regex: $k unmatched BEGIN lines (${text.length} chars) took ${(System.nanoTime() - start) / 1_000_000}ms")
        }
    }

    // ---------------- confirmed bugs (ignored so the suite stays green) ----------------

    @Test
    fun rsaEvenPublicExponent_returnsNull() {
        val pkcs1 = rsaPkcs1(BigInteger.valueOf(65_538))
        assertNull(derive(pem("RSA PRIVATE KEY", pkcs1.encoded)))
        val pkcs8 = PrivateKeyInfo(AlgorithmIdentifier(PKCSObjectIdentifiers.rsaEncryption, DERNull.INSTANCE), pkcs1)
        assertNull(derive(pem("PRIVATE KEY", pkcs8.encoded)))
    }

    @Test
    fun dsaZeroModulus_returnsNull() {
        val z = BigInteger.ZERO
        val one = BigInteger.ONE
        assertNull(derive(pem("DSA PRIVATE KEY", derSequence(z, z, one, BigInteger.TWO, one, one))))
    }

    @Test
    fun dsaPkcs8WithoutParameters_returnsNull() {
        val info = PrivateKeyInfo(AlgorithmIdentifier(X9ObjectIdentifiers.id_dsa), ASN1Integer(BigInteger.TEN))
        assertNull(derive(pem("PRIVATE KEY", info.encoded)))
        val withParams = PrivateKeyInfo(
            AlgorithmIdentifier(X9ObjectIdentifiers.id_dsa, DSAParameter(BigInteger.ZERO, BigInteger.ONE, BigInteger.TWO)),
            ASN1Integer(BigInteger.TEN)
        )
        assertNull(derive(pem("PRIVATE KEY", withParams.encoded)))
    }

    @Test
    fun pemRegex_manyUnclosedHeaders_withinBudget() {
        val text = "-----BEGIN RSA PRIVATE KEY-----\n".repeat(5_000) + "AAAA" // 160 KB
        Fuzz.guarded("derive unclosed headers", "5k BEGIN lines", budgetMs = 2_000) {
            SshKeyGenerator.derivePublicKeyFromPrivate(text)
        }
    }

    @Test
    fun dsaInconsistentKey_returnsNull() {
        val one = BigInteger.ONE
        // p = 23, q = 11, g = 5 (order 22, not in the q-subgroup), x = 3: y = 10, 10^11 mod 23 != 1.
        val text = pem("DSA PRIVATE KEY", derSequence(BigInteger.ZERO, BigInteger.valueOf(23), BigInteger.valueOf(11), BigInteger.valueOf(5), one, BigInteger.valueOf(3)))
        println("dsaInconsistentKey PEM: ${Fuzz.describe(text)}")
        assertNull(derive(text))
    }

    @Test
    fun dsaHugeModulus_isRejectedQuickly() {
        val rnd = java.util.Random(7)
        var worst = 0L
        listOf(4_096, 8_192, 16_384, 32_768).forEach { bits ->
            val p = BigInteger(bits, rnd).setBit(bits - 1).setBit(0)
            val x = BigInteger(bits, rnd).setBit(bits - 1)
            val text = pem("DSA PRIVATE KEY", derSequence(BigInteger.ZERO, p, BigInteger.ONE, BigInteger.TWO, BigInteger.ONE, x))
            val start = System.nanoTime()
            val outcome = runCatching { SshKeyGenerator.derivePublicKeyFromPrivate(text) }
            val ms = (System.nanoTime() - start) / 1_000_000
            worst = maxOf(worst, ms)
            println("DSA p=$bits bits, PEM ${text.length} chars: derive took ${ms}ms, outcome=${outcome.exceptionOrNull()?.javaClass?.simpleName ?: outcome.getOrNull()}")
        }
        assertTrue("worst ${worst}ms", worst < 1_000)
    }
}
